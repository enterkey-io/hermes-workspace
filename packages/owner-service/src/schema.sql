CREATE TABLE IF NOT EXISTS owner_claim(id INTEGER PRIMARY KEY CHECK(id=1),user_id TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS owner_setup(id INTEGER PRIMARY KEY CHECK(id=1),value TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS owner_limit(key TEXT PRIMARY KEY,start INTEGER NOT NULL,count INTEGER NOT NULL);
CREATE TRIGGER IF NOT EXISTS single_owner BEFORE INSERT ON "user" WHEN EXISTS(SELECT 1 FROM "user") BEGIN SELECT RAISE(ABORT,'single owner'); END;
